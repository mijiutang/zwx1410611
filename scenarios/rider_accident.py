
'''
处理“骑手送餐工具损坏、发生交通事故”的场景。
严格按照流程图的文字和步骤。
'''
from .utils import get_user_choice, show_action

def handle():
    """处理“骑手送餐工具损坏、发生交通事故”的场景。"""
    print("\n--- 开始处理场景：骑手送餐工具损坏、发生交通事故 ---")
    
    show_action(
        "外呼骑手了解情况并确认15min内是否可返餐。",
        "【外呼骑手-配送异常-核实骑手是否可以返餐】同时对商家话术：您好，核实订单因骑手配送时出现异常情况无法继续配送，请您先不要着急我们已联系骑手尽快还餐，并通知安抚用户等待，争议保证订单正常履约不会影响商家订单结算。"
    )

    can_return = get_user_choice(
        "骑手是否可以15min内返餐?",
        ["是", "否/联系不到"]
    )

    if can_return == "是":
        show_action(
            "告知商家骑手返餐，安抚商家等待新的骑手配送。",
            "参考话术：非常抱歉确实影响您餐品送达了，小袋联系骑手确定是可以返餐的，辛苦您耐心等待一会，餐品返回后可以尽快安排新骑手配送。"
        )
    else: # 否/联系不到
        show_action("联系用户是否同意退款。", "【外呼用户-协商订单退款】")
        user_agrees = get_user_choice("用户是否同意退款?", ["是", "否/联系不到"])
        
        if user_agrees == "是":
            show_action("告知商家订单需退款，根据责任方操作（不引导商家自行退款）。")
        else: # 否/联系不到
            show_action(
                "对商家：告知订单保持现状。",
                "参考话术：老板小袋刚联系用户沟通，用户不同意退款，建议您先不要对订单操作退款，后续会有平台介入处理，辛苦您关注一下，有问题随时可以联系我们处理。"
            )
            show_action(
                "对用户：不认可流转纠纷。",
                "参考话术：如果您不同意小袋为您退款的话，小袋帮您反馈给更专业的同事为您处理。"
            )
